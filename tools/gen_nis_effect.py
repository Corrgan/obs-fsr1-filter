#!/usr/bin/env python3
"""Erzeugt data/effects/nis.effect: NVIDIA Image Scaling (NVScaler) als OBS-Effect.

Aufruf:  python3 -I tools/gen_nis_effect.py data/effects/nis.effect

Warum ein Generator? Das Original (NIS_Scaler.h) ist ein Compute-Shader mit Shared Memory
und Arrays. OBS' Effect-Parser ist deutlich eingeschränkter als ein normaler HLSL/GLSL-
Compiler. Die Erfahrungen aus dem FSR-Shader sind hier eingeflossen:

  * keine Arrays: alle 6x6 Luma-Werte sind einzelne float-Variablen
  * kein '#define NAME (...)'  (OBS liest die Klammer als Parameterliste)
  * keine Exponenten-Literale wie 1.0e-8
  * kein ternärer Operator, stattdessen if/else
  * kein Shared Memory: jeder Ausgabepixel berechnet seine Kantenkarte selbst aus den
    36 Punkt-Abtastungen (rechnerisch identisch zum Original)
  * nur Punkt-Sampler; der letzte bilineare Zugriff (Farbe) wird von Hand gemischt
  * die Koeffiziententabellen kommen als Textur (4 x 64, RGBA32F) aus dem Plugin

Algorithmus und Konstanten: NVIDIA Image Scaling (NIS_Scaler.h / NIS_Config.h),
MIT-Lizenz, Copyright (c) 2022 NVIDIA Corporation & Affiliates.
"""
import sys

N = 6  # 6x6 Stützstellen


def p(i, j):
    return "p%d%d" % (i, j)


def build():
    L = []
    a = L.append

    a("// NVIDIA Image Scaling (NVScaler) für OBS Studio")
    a("// GENERIERT von tools/gen_nis_effect.py - nicht von Hand ändern.")
    a("// Algorithmus: NVIDIA Image Scaling (MIT-Lizenz, Copyright (c) 2022 NVIDIA Corporation & Affiliates).")
    a("//")
    a("// Gültig für Skalierungen von 1x bis 2x (wie im Original).")
    a("")
    a("uniform float4x4 ViewProj;")
    a("uniform texture2d image;")
    a("uniform texture2d coef;      // 4 x 64, RGBA32F: Spalte 0/1 = Skalierer, Spalte 2/3 = USM")
    a("")
    a("uniform float2 input_size;   // Quellgröße in Pixeln")
    a("uniform float2 output_size;  // Zielgröße in Pixeln")
    a("uniform float4 nis_detect;   // kDetectRatio, kDetectThres, kMinContrastRatio, kRatioNorm")
    a("uniform float4 nis_sharp1;   // kSharpStartY, kSharpScaleY, kSharpStrengthMin, kSharpStrengthScale")
    a("uniform float4 nis_sharp2;   // kSharpLimitMin, kSharpLimitScale, 0, 0")
    a("")
    a("sampler_state point_clamp {")
    a("\tFilter    = Point;")
    a("\tAddressU  = Clamp;")
    a("\tAddressV  = Clamp;")
    a("};")
    a("")
    a("struct VertData {")
    a("\tfloat4 pos : POSITION;")
    a("\tfloat2 uv  : TEXCOORD0;")
    a("};")
    a("")
    a("VertData VSDefault(VertData v_in)")
    a("{")
    a("\tVertData vert_out;")
    a("\tvert_out.pos = mul(float4(v_in.pos.xyz, 1.0), ViewProj);")
    a("\tvert_out.uv  = v_in.uv;")
    a("\treturn vert_out;")
    a("}")
    a("")
    a("float LumaOf(float3 c)")
    a("{")
    a("\treturn 0.2126 * c.x + 0.7152 * c.y + 0.0722 * c.z;")
    a("}")
    a("")
    a("float3 RgbAt(float2 texel)")
    a("{")
    a("\treturn image.Sample(point_clamp, (texel + 0.5) / input_size).rgb;")
    a("}")
    a("")
    a("float LumaAt(float2 texel)")
    a("{")
    a("\treturn LumaOf(RgbAt(texel));")
    a("}")
    a("")
    a("// Koeffizienten: col 0..3, phase 0..63")
    a("float4 LoadCoef(float col, float phase)")
    a("{")
    a("\treturn coef.Sample(point_clamp, float2((col + 0.5) / 4.0, (phase + 0.5) / 64.0));")
    a("}")
    a("")

    # ---- EdgeMap ----
    a("// Kantengewichte (0, 90, 45, 135 Grad) aus einem 3x3-Fenster.")
    a("float4 EdgeMap(float w00, float w01, float w02,")
    a("\tfloat w10, float w11, float w12,")
    a("\tfloat w20, float w21, float w22)")
    a("{")
    a("\tfloat g_0 = abs(w00 + w01 + w02 - w20 - w21 - w22);")
    a("\tfloat g_45 = abs(w10 + w00 + w01 - w21 - w22 - w12);")
    a("\tfloat g_90 = abs(w00 + w10 + w20 - w02 - w12 - w22);")
    a("\tfloat g_135 = abs(w10 + w20 + w21 - w01 - w02 - w12);")
    a("")
    a("\tfloat g_0_90_max = max(g_0, g_90);")
    a("\tfloat g_0_90_min = min(g_0, g_90);")
    a("\tfloat g_45_135_max = max(g_45, g_135);")
    a("\tfloat g_45_135_min = min(g_45, g_135);")
    a("")
    a("\tfloat4 result = float4(0.0, 0.0, 0.0, 0.0);")
    a("\tif (g_0_90_max + g_45_135_max > 0.0) {")
    a("\t\tfloat e_0_90 = min(g_0_90_max / (g_0_90_max + g_45_135_max), 1.0);")
    a("\t\tfloat e_45_135 = 1.0 - e_0_90;")
    a("")
    a("\t\tbool c_0_90 = (g_0_90_max > (g_0_90_min * nis_detect.x)) && (g_0_90_max > nis_detect.y) && (g_0_90_max > g_45_135_min);")
    a("\t\tbool c_45_135 = (g_45_135_max > (g_45_135_min * nis_detect.x)) && (g_45_135_max > nis_detect.y) && (g_45_135_max > g_0_90_min);")
    a("\t\tbool c_g_0_90 = g_0_90_max == g_0;")
    a("\t\tbool c_g_45_135 = g_45_135_max == g_45;")
    a("")
    a("\t\tfloat f_e_0_90 = 1.0;")
    a("\t\tfloat f_e_45_135 = 1.0;")
    a("\t\tif (c_0_90 && c_45_135) {")
    a("\t\t\tf_e_0_90 = e_0_90;")
    a("\t\t\tf_e_45_135 = e_45_135;")
    a("\t\t}")
    a("")
    a("\t\tfloat weight_0 = 0.0;")
    a("\t\tfloat weight_90 = 0.0;")
    a("\t\tif (c_0_90) {")
    a("\t\t\tif (c_g_0_90) {")
    a("\t\t\t\tweight_0 = f_e_0_90;")
    a("\t\t\t} else {")
    a("\t\t\t\tweight_90 = f_e_0_90;")
    a("\t\t\t}")
    a("\t\t}")
    a("\t\tfloat weight_45 = 0.0;")
    a("\t\tfloat weight_135 = 0.0;")
    a("\t\tif (c_45_135) {")
    a("\t\t\tif (c_g_45_135) {")
    a("\t\t\t\tweight_45 = f_e_45_135;")
    a("\t\t\t} else {")
    a("\t\t\t\tweight_135 = f_e_45_135;")
    a("\t\t\t}")
    a("\t\t}")
    a("\t\tresult = float4(weight_0, weight_90, weight_45, weight_135);")
    a("\t}")
    a("\treturn result;")
    a("}")
    a("")

    # ---- CalcLTI ----
    a("// Reduziert Ringing.")
    a("float CalcLTI(float p0, float p1, float p2, float p3, float p4, float p5, float phase)")
    a("{")
    a("\tfloat sel_a = p3;")
    a("\tfloat sel_b = p5;")
    a("\tif (phase <= 32.0) {")
    a("\t\tsel_a = p0;")
    a("\t\tsel_b = p2;")
    a("\t}")
    a("\tfloat a_min = min(min(p1, p2), sel_a);")
    a("\tfloat a_max = max(max(p1, p2), sel_a);")
    a("\tfloat b_min = min(min(p3, p4), sel_b);")
    a("\tfloat b_max = max(max(p3, p4), sel_b);")
    a("")
    a("\tfloat a_cont = a_max - a_min;")
    a("\tfloat b_cont = b_max - b_min;")
    a("")
    a("\t// kEps = 1/255, kContrastBoost = 1")
    a("\tfloat cont_ratio = max(a_cont, b_cont) / (min(a_cont, b_cont) + 0.003921569);")
    a("\treturn 1.0 - saturate((cont_ratio - nis_detect.z) * nis_detect.w);")
    a("}")
    a("")

    # ---- EvalPoly6 ----
    a("// 6-Tap-Filter plus adaptives Unsharp-Masking für eine Zeile/Spalte von 6 Werten.")
    a("float EvalPoly6(float a0, float a1, float a2, float a3, float a4, float a5, float phase)")
    a("{")
    a("\tfloat4 s0 = LoadCoef(0.0, phase);")
    a("\tfloat4 s1 = LoadCoef(1.0, phase);")
    a("\tfloat4 u0 = LoadCoef(2.0, phase);")
    a("\tfloat4 u1 = LoadCoef(3.0, phase);")
    a("")
    a("\tfloat y = s0.x * a0 + s0.y * a1 + s0.z * a2 + s0.w * a3 + s1.x * a4 + s1.y * a5;")
    a("\tfloat y_usm = u0.x * a0 + u0.y * a1 + u0.z * a2 + u0.w * a3 + u1.x * a4 + u1.y * a5;")
    a("")
    a("\t// stückweise Rampe über der Helligkeit")
    a("\tfloat y_scale = 1.0 - saturate((y - nis_sharp1.x) * nis_sharp1.y);")
    a("")
    a("\t// Schärfe als Funktion der Helligkeit")
    a("\tfloat y_sharpness = y_scale * nis_sharp1.w + nis_sharp1.z;")
    a("\ty_usm = y_usm * y_sharpness;")
    a("")
    a("\t// USM als Funktion der Helligkeit begrenzen")
    a("\tfloat y_sharpness_limit = (y_scale * nis_sharp2.y + nis_sharp2.x) * y;")
    a("\ty_usm = min(y_sharpness_limit, max(-y_sharpness_limit, y_usm));")
    a("")
    a("\t// Ringing reduzieren")
    a("\ty_usm = y_usm * CalcLTI(a0, a1, a2, a3, a4, a5, phase);")
    a("")
    a("\treturn y + y_usm;")
    a("}")
    a("")

    # ---- Pixel shader ----
    a("float4 PSNis(VertData v_in) : TARGET")
    a("{")
    a("\t// Ausgabepixel -> Position im Quellbild")
    a("\tfloat2 dst = floor(v_in.uv * output_size);")
    a("\tfloat2 ratio = input_size / output_size;")
    a("\tfloat2 srcpos = (dst + 0.5) * ratio - 0.5;")
    a("\tfloat2 srcfloor = floor(srcpos);")
    a("\tfloat fx = srcpos.x - srcfloor.x;")
    a("\tfloat fy = srcpos.y - srcfloor.y;")
    a("\tfloat fx_int = min(floor(fx * 64.0), 63.0);")
    a("\tfloat fy_int = min(floor(fy * 64.0), 63.0);")
    a("")
    a("\t// 6x6 Luma-Stützstellen, p<Zeile><Spalte>; Zeile = y, Spalte = x.")
    a("\t// p22 ist der Quellpixel srcfloor.")
    a("\tfloat2 origin = srcfloor - 2.0;")
    for i in range(N):
        for j in range(N):
            a("\tfloat %s = LumaAt(origin + float2(%d.0, %d.0));" % (p(i, j), j, i))
    a("")

    # Edge maps: edge[i][j] nutzt 3x3-Fenster mit Ecke p[1+i][1+j]
    a("\t// Kantenkarte an den vier Eckpunkten um die Abtastposition")
    for i in range(2):
        for j in range(2):
            args = []
            for r in range(3):
                for c in range(3):
                    args.append(p(1 + i + r, 1 + j + c))
            a("\tfloat4 e%d%d = EdgeMap(%s);" % (i, j, ", ".join(args)))
    a("\tfloat4 w = lerp(lerp(e00, e01, fx), lerp(e10, e11, fx), fy);")
    a("")

    a("\t// Normaler 6x6-Skalierer")
    a("\tfloat4 sx0 = LoadCoef(0.0, fx_int);")
    a("\tfloat4 sx1 = LoadCoef(1.0, fx_int);")
    a("\tfloat4 sy0 = LoadCoef(0.0, fy_int);")
    a("\tfloat4 sy1 = LoadCoef(1.0, fy_int);")
    for j in range(N):
        terms = []
        wy = ["sy0.x", "sy0.y", "sy0.z", "sy0.w", "sy1.x", "sy1.y"]
        for i in range(N):
            terms.append("%s * %s" % (p(i, j), wy[i]))
        a("\tfloat v%d = %s;" % (j, " + ".join(terms)))
    a("\tfloat normal_y = v0 * sx0.x + v1 * sx0.y + v2 * sx0.z + v3 * sx0.w + v4 * sx1.x + v5 * sx1.y;")
    a("")
    a("\tfloat dir_y = 0.0;")
    a("")

    # 0 deg
    a("\tif (w.x > 0.0) {")
    a("\t\t// 0 Grad: horizontal zwischen Spalte 2 und 3 mischen, vertikal filtern")
    for i in range(N):
        a("\t\tfloat h%d = lerp(%s, %s, fx);" % (i, p(i, 2), p(i, 3)))
    a("\t\tdir_y += EvalPoly6(h0, h1, h2, h3, h4, h5, fy_int) * w.x;")
    a("\t}")
    a("")

    # 90 deg
    a("\tif (w.y > 0.0) {")
    a("\t\t// 90 Grad: vertikal zwischen Zeile 2 und 3 mischen, horizontal filtern")
    for i in range(N):
        a("\t\tfloat k%d = lerp(%s, %s, fy);" % (i, p(2, i), p(3, i)))
    a("\t\tdir_y += EvalPoly6(k0, k1, k2, k3, k4, k5, fx_int) * w.y;")
    a("\t}")
    a("")

    # 45 deg
    a("\tif (w.z > 0.0) {")
    a("\t\t// 45 Grad")
    a("\t\tfloat pb45 = 0.5 + 0.5 * (fx - fy);")
    a("\t\tfloat t45_1 = lerp(%s, %s, pb45);" % (p(2, 1), p(1, 2)))
    a("\t\tfloat t45_3 = lerp(%s, %s, pb45);" % (p(3, 2), p(2, 3)))
    a("\t\tfloat t45_5 = lerp(%s, %s, pb45);" % (p(4, 3), p(3, 4)))
    a("\t\tfloat pb45s = pb45 - 0.5;")
    a("\t\tfloat sa45 = %s;" % p(2, 0))
    a("\t\tfloat sb45 = %s;" % p(3, 1))
    a("\t\tfloat sc45 = %s;" % p(4, 2))
    a("\t\tfloat sd45 = %s;" % p(5, 3))
    a("\t\tif (pb45s >= 0.0) {")
    a("\t\t\tsa45 = %s;" % p(0, 2))
    a("\t\t\tsb45 = %s;" % p(1, 3))
    a("\t\t\tsc45 = %s;" % p(2, 4))
    a("\t\t\tsd45 = %s;" % p(3, 5))
    a("\t\t}")
    a("\t\tfloat t45_0 = lerp(%s, sa45, abs(pb45s));" % p(1, 1))
    a("\t\tfloat t45_2 = lerp(%s, sb45, abs(pb45s));" % p(2, 2))
    a("\t\tfloat t45_4 = lerp(%s, sc45, abs(pb45s));" % p(3, 3))
    a("\t\tfloat t45_6 = lerp(%s, sd45, abs(pb45s));" % p(4, 4))
    a("")
    a("\t\tfloat pp45 = fx + fy;")
    a("\t\tfloat i45_0 = t45_0;")
    a("\t\tfloat i45_1 = t45_1;")
    a("\t\tfloat i45_2 = t45_2;")
    a("\t\tfloat i45_3 = t45_3;")
    a("\t\tfloat i45_4 = t45_4;")
    a("\t\tfloat i45_5 = t45_5;")
    a("\t\tif (pp45 >= 1.0) {")
    a("\t\t\ti45_0 = t45_1;")
    a("\t\t\ti45_1 = t45_2;")
    a("\t\t\ti45_2 = t45_3;")
    a("\t\t\ti45_3 = t45_4;")
    a("\t\t\ti45_4 = t45_5;")
    a("\t\t\ti45_5 = t45_6;")
    a("\t\t\tpp45 = pp45 - 1.0;")
    a("\t\t}")
    a("\t\tdir_y += EvalPoly6(i45_0, i45_1, i45_2, i45_3, i45_4, i45_5, min(floor(pp45 * 64.0), 63.0)) * w.z;")
    a("\t}")
    a("")

    # 135 deg
    a("\tif (w.w > 0.0) {")
    a("\t\t// 135 Grad")
    a("\t\tfloat pb135 = 0.5 * (fx + fy);")
    a("\t\tfloat t135_1 = lerp(%s, %s, pb135);" % (p(3, 1), p(4, 2)))
    a("\t\tfloat t135_3 = lerp(%s, %s, pb135);" % (p(2, 2), p(3, 3)))
    a("\t\tfloat t135_5 = lerp(%s, %s, pb135);" % (p(1, 3), p(2, 4)))
    a("\t\tfloat pb135s = pb135 - 0.5;")
    a("\t\tfloat sa135 = %s;" % p(3, 0))
    a("\t\tfloat sb135 = %s;" % p(2, 1))
    a("\t\tfloat sc135 = %s;" % p(1, 2))
    a("\t\tfloat sd135 = %s;" % p(0, 3))
    a("\t\tif (pb135s >= 0.0) {")
    a("\t\t\tsa135 = %s;" % p(5, 2))
    a("\t\t\tsb135 = %s;" % p(4, 3))
    a("\t\t\tsc135 = %s;" % p(3, 4))
    a("\t\t\tsd135 = %s;" % p(2, 5))
    a("\t\t}")
    a("\t\tfloat t135_0 = lerp(%s, sa135, abs(pb135s));" % p(4, 1))
    a("\t\tfloat t135_2 = lerp(%s, sb135, abs(pb135s));" % p(3, 2))
    a("\t\tfloat t135_4 = lerp(%s, sc135, abs(pb135s));" % p(2, 3))
    a("\t\tfloat t135_6 = lerp(%s, sd135, abs(pb135s));" % p(1, 4))
    a("")
    a("\t\tfloat pp135 = 1.0 + (fx - fy);")
    a("\t\tfloat i135_0 = t135_0;")
    a("\t\tfloat i135_1 = t135_1;")
    a("\t\tfloat i135_2 = t135_2;")
    a("\t\tfloat i135_3 = t135_3;")
    a("\t\tfloat i135_4 = t135_4;")
    a("\t\tfloat i135_5 = t135_5;")
    a("\t\tif (pp135 >= 1.0) {")
    a("\t\t\ti135_0 = t135_1;")
    a("\t\t\ti135_1 = t135_2;")
    a("\t\t\ti135_2 = t135_3;")
    a("\t\t\ti135_3 = t135_4;")
    a("\t\t\ti135_4 = t135_5;")
    a("\t\t\ti135_5 = t135_6;")
    a("\t\t\tpp135 = pp135 - 1.0;")
    a("\t\t}")
    a("\t\tdir_y += EvalPoly6(i135_0, i135_1, i135_2, i135_3, i135_4, i135_5, min(floor(pp135 * 64.0), 63.0)) * w.w;")
    a("\t}")
    a("")

    a("\t// Endhelligkeit: gewichtete Summe aus normalem und gerichtetem Filter")
    a("\tfloat base_weight = 1.0 - w.x - w.y - w.z - w.w;")
    a("\tfloat op_y = normal_y * base_weight + dir_y;")
    a("")
    a("\t// Farbe: bilinear zwischen den vier Quellpixeln um die Abtastposition (von Hand,")
    a("\t// entspricht dem Linear-Clamp-Zugriff des Originals), dann Helligkeit angleichen")
    a("\tfloat3 c00 = RgbAt(srcfloor);")
    a("\tfloat3 c01 = RgbAt(srcfloor + float2(1.0, 0.0));")
    a("\tfloat3 c10 = RgbAt(srcfloor + float2(0.0, 1.0));")
    a("\tfloat3 c11 = RgbAt(srcfloor + float2(1.0, 1.0));")
    a("\tfloat3 rgb = lerp(lerp(c00, c01, fx), lerp(c10, c11, fx), fy);")
    a("\tfloat y_now = LumaOf(rgb);")
    a("\tfloat corr = op_y - y_now;")
    a("\trgb = saturate(rgb + float3(corr, corr, corr));")
    a("\treturn float4(rgb, 1.0);")
    a("}")
    a("")
    a("technique NIS")
    a("{")
    a("\tpass")
    a("\t{")
    a("\t\tvertex_shader = VSDefault(v_in);")
    a("\t\tpixel_shader  = PSNis(v_in);")
    a("\t}")
    a("}")
    a("")
    return "\n".join(L)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    text = build()
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write(text)
    print("OK: %s (%d Zeilen)" % (sys.argv[1], text.count("\n")))


if __name__ == "__main__":
    main()
